function svgWrap(inner, w, h) {
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="0 0 ${w} ${h}" aria-hidden="true">${inner}</svg>`;
}

function box(x, y, s) {
  return `<rect x="${x}" y="${y}" width="${s}" height="${s}" fill="#fffaf0" stroke="#1c1712" stroke-width="1.5"/>`;
}

function shapeAt(cx, cy, kind, fill) {
  const stroke = "#1c1712";
  let paint = "none";
  let extra = "";
  if (fill === "solid") paint = "#1c1712";
  if (fill === "stripe") {
    extra = `<pattern id="p${cx}${cy}" width="6" height="6" patternUnits="userSpaceOnUse"><path d="M0,6 L6,0" stroke="#1c1712" stroke-width="1.4"/></pattern>`;
    paint = `url(#p${cx}${cy})`;
  }
  if (kind === "circle") {
    return `${extra}<circle cx="${cx}" cy="${cy}" r="18" fill="${paint}" stroke="${stroke}" stroke-width="2"/>`;
  }
  if (kind === "square") {
    return `${extra}<rect x="${cx - 17}" y="${cy - 17}" width="34" height="34" fill="${paint}" stroke="${stroke}" stroke-width="2"/>`;
  }
  return `${extra}<polygon points="${cx},${cy - 20} ${cx + 18},${cy + 16} ${cx - 18},${cy + 16}" fill="${paint}" stroke="${stroke}" stroke-width="2"/>`;
}

